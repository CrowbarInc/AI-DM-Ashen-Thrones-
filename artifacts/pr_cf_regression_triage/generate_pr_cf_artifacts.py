def file_from_class(classname: str) -> str:
    return classname.replace(".", "/") + ".py"


def classify(path: str, name: str, msg: str, text: str) -> str:
    blob = " ".join([path, name, msg, text]).lower()
    if "filenotfounderror" in blob and "pytest_lastfailed" in blob:
        return "H_ENV_BASETEMP_SETUP_NOISE"
    if "socketpair" in blob or "_make_self_pipe" in blob:
        return "H_TESTCLIENT_SOCKETPAIR_HANG"
    if "live model/ap" in blob or "call_gpt" in blob:
        return "F_LIVE_MODEL_GUARD"
    if (
        "cross-file duplicate test name" in blob
        or "compat" in blob
        or "import guard" in blob
        or "static importer count" in blob
    ):
        return "G_GOVERNANCE_EXPECTATION_DRIFT"
    if "speaker_contract.mismatch_present" in blob:
        return "C_SPEAKER_CONTRACT_MISMATCH"
    if (
        "player_facing_text" in blob
        or "final_emitted_source" in blob
        or "fallback" in blob
        or "emitted" in blob
    ):
        return "B_NARRATION_RESPONSE_PROJECTION"
    if (
        "reply_kind" in blob
        or "refusal" in blob
        or "uncertainty" in blob
        or "social" in blob
        or "dialogue" in blob
        or "speaker" in blob
    ):
        return "A_SOCIAL_REPLY_PLANNING"
    if "resolution" in blob or "investigate" in blob or "observe" in blob or "discovery" in blob:
        return "E_EXPLORATION_INVESTIGATION"
    if "prompt" in blob or "provider-visible" in blob or "narrative roles" in blob or "guidance" in blob:
        return "G_TEST_EXPECTATION_DRIFT"
    if "reactive" in path or "objective_resolved" in blob or "max_intent_attempts" in blob:
        return "D_REACTIVE_TURN_PIPELINE"
    if "lead" in blob or "state" in blob or "provenance" in blob or "ownership" in blob:
        return "C_AUTHORITY_STATE_PROVENANCE"
    return "I_OTHER"


def flags(path: str, name: str, text: str, msg: str) -> dict:
    blob = " ".join([path, name, text, msg]).lower()
    return {
        "http_or_testclient_involved": any(k in blob for k in ["http", "testclient", "api_chat", "client."]),
        "social_reply_planning_involved": any(
            k in blob for k in ["social", "speaker", "dialogue", "npc", "reply", "refusal", "uncertainty"]
        ),
        "narration_generation_involved": any(
            k in blob for k in ["narration", "final_emission", "emitted", "prose", "fallback", "player_facing_text"]
        ),
        "authority_state_provenance_involved": any(
            k in blob
            for k in [
                "authority",
                "provenance",
                "ownership",
                "state",
                "mutation",
                "lead",
                "contract",
                "authorized",
                "unauthorized",
                "speaker_contract",
            ]
        ),
    }


def run(args: list[str]) -> str:
    return subprocess.run(args, capture_output=True, text=True, check=False).stdout.strip()


root = ET.parse(XML_PATH).getroot()
records = []
for case in root.findall(".//testcase"):
    failure = case.find("failure")
    error = case.find("error")
    node = failure if failure is not None else error
    if node is None:
        continue
    path = file_from_class(case.attrib.get("classname", ""))
    name = case.attrib.get("name", "")
    kind = "failure" if failure is not None else "error"
    msg = node.attrib.get("message", "")
    text = node.text or ""
    signature = classify(path, name, msg, text)
    expected = None
    actual = None
    match = re.search(r"assert (.+?) == (.+?)(?:\n|$)", text)
    if match:
        actual = match.group(1)[:200]
        expected = match.group(2)[:200]
    records.append(
        {
            "test_file": path,
            "test_name": name,
            "outcome_kind": kind,
            "assertion_failure": msg[:1000],
            "expected_result": expected,
            "actual_result": actual,
            "relevant_traceback": "\n".join((text or msg).splitlines()[-12:]),
            "implicated_application_component": signature,
            "common_assertion_signature": signature,
            **flags(path, name, text, msg),
            "inventory_caveat": (
                "PR-CE authoritative broad count preserved; this diagnostic JUnit was generated by PR-CF. "
                "161 setup errors are PR-CF basetemp noise, not application failures."
                if signature == "H_ENV_BASETEMP_SETUP_NOISE"
                else ""
            ),
        }
    )

by_sig = collections.Counter(r["common_assertion_signature"] for r in records)
by_file = collections.Counter(r["test_file"] for r in records)
